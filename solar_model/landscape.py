"""Deterministic, bounded-cost landscape meshes, built once per site design.

Foliage, bark, grass and stones are batched by material. No landscape geometry
is regenerated by the animation loop and no external textures are downloaded.
"""
from functools import lru_cache

import numpy as np
import pyvista as pv

from .mechanics import layout

FOLIAGE="#4b7d3e"
GRASS="#759548"
BARK="#6a5138"
STONE="#a99b81"
CONTACT="#345330"


def is_arid(c):
    return c.altitude_m < 900 and c.site not in ("Mombasa","Kisumu")


def height(x,y,d):
    outside=np.maximum(np.maximum(np.abs(x)-d["fence_half_x"]-2,np.abs(y)-d["fence_half_y"]-2),0)
    hills=7*np.exp(-((x+27)**2+(y-48)**2)/550)+10*np.exp(-((x-35)**2+(y-64)**2)/750)
    return (.2*np.sin(x*.18)*np.cos(y*.20)+hills)*np.clip(outside/10,0,1)-.025


def ground_colors(x,y,c,d):
    """Meadow variation, a gravel compound, and a distinct entrance track."""
    x,y=np.asarray(x),np.asarray(y)
    arid=is_arid(c)
    def noise(scale):
        u,v=x/scale,y/scale
        i,j=np.floor(u),np.floor(v)
        u,v=u-i,v-j
        u,v=u*u*(3-2*u),v*v*(3-2*v)
        def corner(dx,dy):
            value=np.sin((i+dx)*127.1+(j+dy)*311.7)*43758.5453
            return (value-np.floor(value))*2-1
        return (corner(0,0)*(1-u)+corner(1,0)*u)*(1-v)+(corner(0,1)*(1-u)+corner(1,1)*u)*v
    broad=noise(7)*1.4+noise(2)*.65+noise(.7)*.25
    fine=np.sin(x*7.13+y*5.87)*np.cos(y*8.71-x*6.31)
    base=np.array([148,118,81] if arid else [83,121,58])
    colors=base+broad[...,None]*[7,10,4]+fine[...,None]*[4,5,2]
    inside=(np.abs(x)<d["fence_half_x"])&(np.abs(y)<d["fence_half_y"])
    colors=np.where(inside[...,None],np.array([166,160,140])+fine[...,None]*10,colors)
    road=(np.abs(x-1)<1.75)&(y<-d["fence_half_y"])
    colors=np.where(road[...,None],np.array([154,131,99])+fine[...,None]*7,colors)
    return np.clip(colors,0,255).astype(np.uint8)


def terrain(c,d):
    # More samples around the compound, fewer on the distant slopes. This
    # preserves small ground details without uniformly tessellating the horizon.
    x=np.r_[np.linspace(-65,-30,15,endpoint=False),np.linspace(-30,30,101,endpoint=False),np.linspace(30,65,16)]
    y=np.r_[np.linspace(-60,-32,12,endpoint=False),np.linspace(-32,42,123,endpoint=False),np.linspace(42,85,17)]
    xx,yy=np.meshgrid(x,y,indexing="ij")
    points=np.column_stack([xx.ravel(),yy.ravel(),height(xx,yy,d).ravel()]).astype(np.float32)
    ids=np.arange(len(points)).reshape(xx.shape)
    a,b,e,f=ids[:-1,:-1].ravel(),ids[1:,:-1].ravel(),ids[1:,1:].ravel(),ids[:-1,1:].ravel()
    faces=np.concatenate([np.column_stack([np.full(len(a),3),a,b,e]),np.column_stack([np.full(len(a),3),a,e,f])])
    mesh=pv.PolyData(points,faces)
    mesh.point_data["terrain_rgb"]=ground_colors(points[:,0],points[:,1],c,d)
    return mesh,is_arid(c)


@lru_cache(maxsize=2)
def _crown_template(detail=1):
    mesh=pv.Icosphere(radius=1,nsub=detail)
    return np.array(mesh.points),mesh.faces.copy()


def _colored_mesh(points,faces,colors,name):
    mesh=pv.PolyData(np.asarray(points,np.float32),np.asarray(faces))
    mesh.point_data[name]=np.asarray(colors,np.uint8)
    return mesh


def _branches(segments):
    """Tapered six-sided branches in one array, with no hidden end caps."""
    starts=np.array([s[0] for s in segments])
    ends=np.array([s[1] for s in segments])
    axis=ends-starts
    axis/=np.linalg.norm(axis,axis=1)[:,None]
    reference=np.tile([0.,0.,1.],(len(axis),1))
    reference[np.abs(axis[:,2])>.9]=[0,1,0]
    u=np.cross(axis,reference)
    u/=np.linalg.norm(u,axis=1)[:,None]
    v=np.cross(axis,u)
    angle=np.arange(6)*np.pi/3
    ring=u[:,None,:]*np.cos(angle)[None,:,None]+v[:,None,:]*np.sin(angle)[None,:,None]
    r0=np.array([s[2] for s in segments])[:,None,None]
    r1=np.array([s[3] for s in segments])[:,None,None]
    points=np.concatenate([starts[:,None,:]+ring*r0,ends[:,None,:]+ring*r1],axis=1)
    base=np.arange(len(axis))[:,None]*12+np.arange(6)[None,:]
    following=(base//12)*12+(base+1)%6
    faces=np.stack([np.full_like(base,4),base,following,following+6,base+6],axis=2)
    return pv.PolyData(points.astype(np.float32).reshape(-1,3),faces.reshape(-1,5))


def _tree(x,y,size,rng,arid,ground):
    """Branching silhouettes with irregular clustered crowns and small leaves."""
    origin=np.array([x,y,ground])
    # Acacia-like spreading crowns alternate with fuller highland silhouettes.
    spreading=arid or rng.random()<.48
    crown_z=2.35 if spreading else 2.65
    crown_width=1.55 if spreading else 1.12
    segments=[]
    trunk=[origin,origin+size*np.array([.07,0,.80]),origin+size*np.array([.11,.02,1.55])]
    segments.extend([(trunk[0],trunk[1],size*.11,size*.083),(trunk[1],trunk[2],size*.083,size*.056)])
    centers=[]
    rotation=rng.uniform(0,2*np.pi)
    for j in range(6):
        angle=rotation+j*np.pi/3+rng.uniform(-.16,.16)
        direction=np.array([np.cos(angle),np.sin(angle),0.])
        elbow=trunk[-1]+size*(direction*.58+[0,0,.30])
        tip=origin+size*(direction*crown_width*.75+[0,0,crown_z+rng.uniform(-.15,.18)])
        segments.extend([(trunk[-1],elbow,size*.050,size*.028),(elbow,tip,size*.028,size*.011)])
        centers.append(tip)
        centers.append(tip+size*np.array([rng.uniform(-.35,.35),rng.uniform(-.32,.32),rng.uniform(.04,.26)]))
    centers.append(origin+size*np.array([.05,0,crown_z+.12]))
    points_all,faces_all,colors_all=[],[],[]
    base_color=np.array([100,124,55] if arid else [53,105,49])
    vertex_offset=0
    for index,center in enumerate(centers):
        # Three main crown lobes use a smoother cached template. Secondary
        # clusters stay coarse; this concentrates triangles on the silhouette.
        template,faces=_crown_template(2 if index in (0,6,12) else 1)
        radii=size*np.array([rng.uniform(.48,.68),rng.uniform(.43,.64),rng.uniform(.31,.43) if spreading else rng.uniform(.52,.67)])
        radial=1+rng.uniform(-.085,.085,(len(template),1))
        points=template*radii*radial+center
        tint=rng.uniform(-11,15)+template[:,2:3]*9
        colors=np.clip(base_color+tint+np.array([0,4,-1]),0,255)
        cells=faces.reshape(-1,4).copy()
        cells[:,1:]+=vertex_offset
        points_all.append(points)
        faces_all.append(cells)
        colors_all.append(colors)
        vertex_offset+=len(points)
    # Tiny three-point leaf fans break up the crown outline. They share the
    # foliage actor, so detail adds no draw calls per tree or per leaf.
    count=72 if np.hypot(x,y)<38 else 40
    for _ in range(count):
        center=centers[rng.integers(len(centers))]
        normal=rng.normal(size=3)
        normal/=np.linalg.norm(normal)
        point=center+normal*size*np.array([.58,.54,.36 if spreading else .57])
        u=np.cross(normal,[0,0,1])
        if np.linalg.norm(u)<.01:
            u=np.cross(normal,[0,1,0])
        u/=np.linalg.norm(u)
        v=np.cross(normal,u)
        length=size*rng.uniform(.08,.16)
        leaf=np.array([point-u*length*.45,point+u*length*.45,point+v*length])
        points_all.append(leaf)
        faces_all.append(np.array([[3,vertex_offset,vertex_offset+1,vertex_offset+2]]))
        colors_all.append(np.tile(np.clip(base_color+[15,23,3]+rng.uniform(-8,8),0,255),(3,1)))
        vertex_offset+=3
    foliage=_colored_mesh(np.concatenate(points_all),np.concatenate(faces_all),np.concatenate(colors_all),"foliage_rgb")
    return _branches(segments),foliage,crown_width*size


def _grass(c,d,rng):
    # Crossed tapered blades only in the near meadow. Distant grass is vertex
    # colour, avoiding thousands of tiny far-away drawables or alpha textures.
    xy=rng.uniform([-31,-28],[31,38],(2600,2))
    clear=(np.abs(xy[:,0])>d["fence_half_x"]+.6)|(np.abs(xy[:,1])>d["fence_half_y"]+.6)
    track=(np.abs(xy[:,0]-1)<2.0)&(xy[:,1]<-d["fence_half_y"])
    xy=xy[clear&~track]
    n=len(xy)
    if n==0:
        return pv.PolyData()
    centers=np.column_stack([xy,height(xy[:,0],xy[:,1],d)+.01])
    angles=rng.uniform(0,2*np.pi,n*3)
    blades=np.repeat(centers,3,axis=0)
    widths=rng.uniform(.025,.05,n*3)
    heights=rng.uniform(.10,.24,n*3)*(0.7 if is_arid(c) else 1)
    across=np.column_stack([np.cos(angles),np.sin(angles),np.zeros(n*3)])
    points=np.stack([blades-across*widths[:,None],blades+across*widths[:,None],
        blades+across*widths[:,None]*.8+np.column_stack([np.zeros(n*3),np.zeros(n*3),heights])],axis=1)
    base=np.array([142,137,73] if is_arid(c) else [87,132,54])
    tint=rng.uniform(-16,18,(n*3,1,1))
    colors=np.tile(base,(n*3,3,1))+tint
    colors[:,2,:]+=[12,17,3]
    faces=np.column_stack([np.full(n*3,3),np.arange(n*9).reshape(-1,3)])
    return _colored_mesh(points.reshape(-1,3),faces,np.clip(colors.reshape(-1,3),0,255),"grass_rgb")


def _contact_shade(trees,d):
    points,faces,colors=[],[],[]
    for x,y,radius in trees:
        start=len(points)
        points.append((x,y,float(height(x,y,d))+.012))
        colors.append((35,57,31,58))
        for angle in np.linspace(0,2*np.pi,17)[:-1]:
            px,py=x+radius*np.cos(angle),y+radius*.76*np.sin(angle)
            points.append((px,py,float(height(px,py,d))+.012))
            colors.append((35,57,31,0))
        for j in range(16):
            faces.append((3,start,start+1+j,start+1+(j+1)%16))
    return _colored_mesh(points,faces,colors,"contact_rgba")


def vegetation(c):
    d=layout(c)
    rng=np.random.default_rng(22)
    branches,foliage,trees=[],[],[]
    # Keep complete trees close enough to the installation for the viewport's
    # clipping range. The far hills remain terrain, rather than partial trees
    # cut by a compound-focused camera's far plane.
    extent=np.array([d["fence_half_x"]+8,d["fence_half_y"]+8])
    candidates=rng.uniform(-extent,extent,(34,2))
    sizes=rng.uniform(1.08,1.78,34)
    for i,((x,y),size) in enumerate(zip(candidates,sizes)):
        clearance=2.8*size
        if abs(x)<d["fence_half_x"]+clearance and abs(y)<d["fence_half_y"]+clearance:
            continue
        trunk,crown,radius=_tree(x,y,size,np.random.default_rng(1000+i),is_arid(c),float(height(x,y,d)))
        branches.append(trunk)
        foliage.append(crown)
        trees.append((x,y,radius))
    rocks=[]
    template,faces=_crown_template(0)
    for _ in range(64):
        x,y=rng.uniform(-35,35),rng.uniform(-29,40)
        if abs(x)<d["fence_half_x"]+1 and abs(y)<d["fence_half_y"]+1:
            continue
        size=rng.uniform(.10,.38)
        points=template*[size*1.5,size,size*.6]+[x,y,float(height(x,y,d))+.04]
        rgb=np.tile(np.array([151,143,116])+rng.uniform(-18,18),(len(points),1))
        rocks.append(_colored_mesh(points,faces,np.clip(rgb,0,255),"stone_rgb"))
    solids={}
    if branches:
        solids[BARK]=pv.merge(branches,merge_points=False)
        solids[FOLIAGE]=pv.merge(foliage,merge_points=False)
        solids[CONTACT]=_contact_shade(trees,d)
    grass=_grass(c,d,rng)
    if grass.n_points:
        solids[GRASS]=grass
    if rocks:
        solids[STONE]=pv.merge(rocks,merge_points=False)
    return solids,{}
